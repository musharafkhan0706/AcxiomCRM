-- V1__create_schema.sql: ACXIOMCRM Core Schema

-- 1. Roles table
CREATE TABLE IF NOT EXISTS roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE,
    description VARCHAR(255)
);

-- 2. Users table
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role_id BIGINT NOT NULL,
    department VARCHAR(100),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    failed_login_count INT NOT NULL DEFAULT 0,
    is_locked BOOLEAN NOT NULL DEFAULT FALSE,
    lockout_time TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_users_role FOREIGN KEY (role_id) REFERENCES roles(id)
);

-- 3. Refresh Tokens table
CREATE TABLE IF NOT EXISTS refresh_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    token VARCHAR(255) NOT NULL UNIQUE,
    token_family VARCHAR(100) NOT NULL,
    is_revoked BOOLEAN NOT NULL DEFAULT FALSE,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_refresh_tokens_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

-- 4. Customers table
CREATE TABLE IF NOT EXISTS customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_code VARCHAR(50) NOT NULL UNIQUE,
    customer_name VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    phone VARCHAR(50) NOT NULL UNIQUE,
    company_name VARCHAR(150),
    address VARCHAR(255),
    city VARCHAR(100),
    state VARCHAR(100),
    status VARCHAR(50) NOT NULL DEFAULT 'ACTIVE',
    assigned_to_user_id BIGINT,
    created_by_user_id BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_customers_assigned_to FOREIGN KEY (assigned_to_user_id) REFERENCES users(id),
    CONSTRAINT fk_customers_created_by FOREIGN KEY (created_by_user_id) REFERENCES users(id)
);

-- 5. Leads table
CREATE TABLE IF NOT EXISTS leads (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lead_code VARCHAR(50) NOT NULL UNIQUE,
    lead_name VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL,
    phone VARCHAR(50) NOT NULL,
    company_name VARCHAR(150),
    source VARCHAR(50) NOT NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'NEW',
    expected_value NUMERIC(15,2) DEFAULT 0.00,
    priority VARCHAR(20) NOT NULL DEFAULT 'MEDIUM',
    assigned_to_user_id BIGINT,
    converted_customer_id BIGINT,
    converted_opportunity_id BIGINT,
    converted_at TIMESTAMP WITH TIME ZONE,
    notes TEXT,
    created_by_user_id BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_leads_assigned_to FOREIGN KEY (assigned_to_user_id) REFERENCES users(id),
    CONSTRAINT fk_leads_converted_customer FOREIGN KEY (converted_customer_id) REFERENCES customers(id),
    CONSTRAINT fk_leads_created_by FOREIGN KEY (created_by_user_id) REFERENCES users(id)
);

-- 6. Opportunities table
CREATE TABLE IF NOT EXISTS opportunities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    opportunity_name VARCHAR(150) NOT NULL,
    customer_id BIGINT NOT NULL,
    lead_id BIGINT,
    amount NUMERIC(15,2) NOT NULL,
    stage VARCHAR(50) NOT NULL DEFAULT 'QUALIFICATION',
    probability INT NOT NULL DEFAULT 20,
    expected_close_date DATE NOT NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'OPEN',
    assigned_to_user_id BIGINT,
    source VARCHAR(50),
    notes TEXT,
    created_by_user_id BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_opportunities_customer FOREIGN KEY (customer_id) REFERENCES customers(id),
    CONSTRAINT fk_opportunities_lead FOREIGN KEY (lead_id) REFERENCES leads(id),
    CONSTRAINT fk_opportunities_assigned_to FOREIGN KEY (assigned_to_user_id) REFERENCES users(id),
    CONSTRAINT fk_opportunities_created_by FOREIGN KEY (created_by_user_id) REFERENCES users(id)
);

-- 7. Follow Ups table
CREATE TABLE IF NOT EXISTS follow_ups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    related_type VARCHAR(50) NOT NULL,
    customer_id BIGINT,
    lead_id BIGINT,
    opportunity_id BIGINT,
    follow_up_date TIMESTAMP WITH TIME ZONE NOT NULL,
    subject VARCHAR(200) NOT NULL,
    follow_up_type VARCHAR(50) NOT NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'PLANNED',
    assigned_to_user_id BIGINT,
    notes TEXT,
    created_by_user_id BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_follow_ups_customer FOREIGN KEY (customer_id) REFERENCES customers(id),
    CONSTRAINT fk_follow_ups_lead FOREIGN KEY (lead_id) REFERENCES leads(id),
    CONSTRAINT fk_follow_ups_opportunity FOREIGN KEY (opportunity_id) REFERENCES opportunities(id),
    CONSTRAINT fk_follow_ups_assigned_to FOREIGN KEY (assigned_to_user_id) REFERENCES users(id),
    CONSTRAINT fk_follow_ups_created_by FOREIGN KEY (created_by_user_id) REFERENCES users(id)
);

-- 8. Activities table
CREATE TABLE IF NOT EXISTS activities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_type VARCHAR(50) NOT NULL,
    subject VARCHAR(200) NOT NULL,
    description TEXT,
    activity_date TIMESTAMP WITH TIME ZONE NOT NULL,
    customer_id BIGINT,
    lead_id BIGINT,
    opportunity_id BIGINT,
    status VARCHAR(50) NOT NULL DEFAULT 'COMPLETED',
    assigned_to_user_id BIGINT,
    created_by_user_id BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_activities_customer FOREIGN KEY (customer_id) REFERENCES customers(id),
    CONSTRAINT fk_activities_lead FOREIGN KEY (lead_id) REFERENCES leads(id),
    CONSTRAINT fk_activities_opportunity FOREIGN KEY (opportunity_id) REFERENCES opportunities(id),
    CONSTRAINT fk_activities_assigned_to FOREIGN KEY (assigned_to_user_id) REFERENCES users(id),
    CONSTRAINT fk_activities_created_by FOREIGN KEY (created_by_user_id) REFERENCES users(id)
);

-- 9. Audit Logs table (Immutable append-only records)
CREATE TABLE IF NOT EXISTS audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    username VARCHAR(150),
    action VARCHAR(100) NOT NULL,
    entity_name VARCHAR(100) NOT NULL,
    record_id VARCHAR(100),
    old_value TEXT,
    new_value TEXT,
    timestamp TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    result VARCHAR(50) NOT NULL DEFAULT 'SUCCESS',
    details TEXT,
    ip_address VARCHAR(100)
);

-- Indexes for optimal querying and reporting performance
CREATE INDEX IF NOT EXISTS idx_users_email ON users(email);
CREATE INDEX IF NOT EXISTS idx_customers_code ON customers(customer_code);
CREATE INDEX IF NOT EXISTS idx_customers_assigned_to ON customers(assigned_to_user_id);
CREATE INDEX IF NOT EXISTS idx_leads_assigned_to ON leads(assigned_to_user_id);
CREATE INDEX IF NOT EXISTS idx_leads_status ON leads(status);
CREATE INDEX IF NOT EXISTS idx_opportunities_stage ON opportunities(stage);
CREATE INDEX IF NOT EXISTS idx_opportunities_assigned_to ON opportunities(assigned_to_user_id);
CREATE INDEX IF NOT EXISTS idx_follow_ups_assigned_to ON follow_ups(assigned_to_user_id);
CREATE INDEX IF NOT EXISTS idx_follow_ups_date_status ON follow_ups(follow_up_date, status);
CREATE INDEX IF NOT EXISTS idx_activities_assigned_to ON activities(assigned_to_user_id);
CREATE INDEX IF NOT EXISTS idx_activities_customer ON activities(customer_id);
CREATE INDEX IF NOT EXISTS idx_audit_logs_timestamp ON audit_logs(timestamp);
CREATE INDEX IF NOT EXISTS idx_audit_logs_entity ON audit_logs(entity_name, record_id);

